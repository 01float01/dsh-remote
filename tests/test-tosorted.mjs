import fs from "node:fs";
import assert from "node:assert";
const code = fs.readFileSync(new URL("../gateway/polyfill.js", import.meta.url), "utf8");
delete Array.prototype.toSorted;
delete Array.prototype.toReversed;
delete Array.prototype.toSpliced;
delete Array.prototype.with;
assert.strictEqual(typeof Array.prototype.toSorted, "undefined");
(0, eval)(code);
assert.strictEqual(typeof Array.prototype.toSorted, "function", "toSorted restored");
const orig = [3, 1, 2];
const sorted = orig.toSorted((a, b) => a - b);
assert.deepStrictEqual(sorted, [1, 2, 3], "toSorted sorts copy");
assert.deepStrictEqual(orig, [3, 1, 2], "original unchanged");
assert.deepStrictEqual([1, 2, 3].toReversed(), [3, 2, 1], "toReversed");
assert.deepStrictEqual([1, 2, 3, 4].toSpliced(1, 2, 9), [1, 9, 4], "toSpliced");
assert.deepStrictEqual([1, 2, 3].with(1, 9), [1, 9, 3], "with");
assert.deepStrictEqual([1, 2, 3].with(-1, 9), [1, 2, 9], "with negative");
console.log("TOSORTED POLYFILL UNIT TEST: ALL PASS");
